# tests/test_parse_fidelity.py
from ingest.parse_fidelity import NORMALIZED_FIELDS, find_header, hash_file_rows, parse_file, row_hash

CURRENT_HEADER = ["Run Date","Action","Symbol","Description","Type","Price ($)","Quantity","Commission ($)","Fees ($)","Accrued Interest ($)","Amount ($)","Cash Balance ($)","Settlement Date"]
LEGACY_HEADER = ["Run Date","Action","Symbol","Description","Type","Exchange Quantity","Exchange Currency","Currency","Price","Quantity","Exchange Rate","Commission","Fees","Accrued Interest","Amount","Cash Balance","Settlement Date"]

ROW = {"account_label":"LLC_MAIN","run_date":"08/10/2026","action":"YOU SOLD ASSIGNED CALLS","symbol":" -PLTR260807C155","description":"CALL (PLTR) PALANTIR AUG 07 26 $155 (100 SHS)","type":"Cash","price":"155","quantity":"-200","commission":"","fees":"0.64","accrued_interest":"","amount":"30999.36","cash_balance":"Processing","settlement_date":"08/10/2026","currency":"USD","exchange_rate":""}


def _write(tmp_path, header, rows):
    p = tmp_path / "t.csv"
    p.write_text("\n".join([",".join(header)] + [",".join(r) for r in rows]))
    return str(p)


def test_find_header_skips_preamble():
    rows = [["Trade history export"], ["Generated by Fidelity"], CURRENT_HEADER]
    assert find_header(rows) == 2


def test_parse_current_format(tmp_path):
    p = _write(tmp_path, CURRENT_HEADER, [[ROW["run_date"], ROW["action"], ROW["symbol"], ROW["description"], ROW["type"], ROW["price"], ROW["quantity"], ROW["commission"], ROW["fees"], ROW["accrued_interest"], ROW["amount"], ROW["cash_balance"], ROW["settlement_date"]]])
    out = parse_file(p)
    assert len(out) == 1
    r = out[0]
    assert r["run_date"] == "2026-08-10"
    assert r["settlement_date"] == "2026-08-10"
    assert r["commission"] is None
    assert r["amount"] == "30999.36"
    assert r["currency"] == "USD"


def test_parse_dash_date_format(tmp_path):
    p = _write(tmp_path, CURRENT_HEADER, [["07-06-2026", ROW["action"], ROW["symbol"], ROW["description"], ROW["type"], ROW["price"], ROW["quantity"], ROW["commission"], ROW["fees"], ROW["accrued_interest"], ROW["amount"], ROW["cash_balance"], "07-07-2026"]])
    out = parse_file(p)
    assert len(out) == 1
    r = out[0]
    assert r["run_date"] == "2026-07-06"
    assert r["settlement_date"] == "2026-07-07"


def test_parse_skips_footer_junk(tmp_path):
    rows = [CURRENT_HEADER,
            [ROW["run_date"], ROW["action"], ROW["symbol"], ROW["description"], ROW["type"], ROW["price"], ROW["quantity"], ROW["commission"], ROW["fees"], ROW["accrued_interest"], ROW["amount"], ROW["cash_balance"], ROW["settlement_date"]],
            ["The data and information in this spreadsheet is provided to you solely for your use and is not for distribution."],
            ["Date downloaded 06/25/2026 9:54 am"]]
    p = tmp_path / "t.csv"
    p.write_text("\n".join([",".join(row) for row in rows]))
    out = parse_file(str(p))
    assert len(out) == 1
    assert out[0]["run_date"] == "2026-08-10"


def test_parse_file_reports_dropped_rows(tmp_path, caplog):
    import logging
    rows = [CURRENT_HEADER,
            [ROW["run_date"], ROW["action"], ROW["symbol"], ROW["description"], ROW["type"], ROW["price"], ROW["quantity"], ROW["commission"], ROW["fees"], ROW["accrued_interest"], ROW["amount"], ROW["cash_balance"], ROW["settlement_date"]],
            ["Date downloaded 06/25/2026 9:54 am"],
            ["The data and information in this spreadsheet is provided to you solely for your use."]]
    p = tmp_path / "t.csv"
    p.write_text("\n".join([",".join(row) for row in rows]))
    with caplog.at_level(logging.WARNING, logger="ingest"):
        out = parse_file(str(p), source_label="History_for_Account_LLC_MAIN (1).csv")
    assert len(out) == 1
    assert "dropped 2 rows" in caplog.text
    assert "History_for_Account_LLC_MAIN (1).csv" in caplog.text


def test_parse_legacy_format_converts_columns(tmp_path):
    row = ["12/29/2023","DIVIDEND RECEIVED","EMD","WESTERN ASSET","Cash","0","","USD","","0","1.0","","","","0.05","2.07",""]
    p = _write(tmp_path, LEGACY_HEADER, [row])
    out = parse_file(p)
    r = out[0]
    assert r["currency"] == "USD"
    assert r["exchange_rate"] == "1.0"
    assert r["price"] is None


def test_parse_skips_header_and_blank_lines(tmp_path):
    p = _write(tmp_path, CURRENT_HEADER, [[ROW["run_date"], "DIVIDEND", "EMD", "d", "Cash", "0", "0", "", "", "", "0.05", "2.07", ""]])
    assert len(parse_file(p)) == 1


def test_row_hash_stable_and_sensitive():
    r1 = dict(ROW)
    r2 = dict(ROW)
    assert row_hash(r1) == row_hash(r2)
    r2["amount"] = "30999.37"
    assert row_hash(r1) != row_hash(r2)
    r3 = dict(ROW)
    r3["account_label"] = "ROTH_IRA"
    assert row_hash(r1) != row_hash(r3)
    r4 = dict(ROW)
    r4["cash_balance"] = "-36874.93"
    assert row_hash(r1) == row_hash(r4)
    assert len(row_hash(r1)) == 32
    assert set(ROW.keys()) == set(NORMALIZED_FIELDS) | {"account_label"}


def test_row_hash_occurrence_distinguishes_identical_trades():
    r1 = dict(ROW)
    r2 = dict(ROW)
    r2["cash_balance"] = "-36874.93"
    assert row_hash(r1, occurrence=1) == row_hash(r2, occurrence=1)
    assert row_hash(r1) == row_hash(r1, occurrence=1)
    assert row_hash(r1, occurrence=1) != row_hash(r1, occurrence=2)


def test_hash_file_rows_collapses_exact_duplicates():
    r1 = dict(ROW)
    r2 = dict(ROW)
    out = hash_file_rows([r1, r2])
    assert len(out) == 1


def test_hash_file_rows_prefers_settled_over_processing():
    settled = dict(ROW, cash_balance="-83232.97")
    processing = dict(ROW)  # ROW carries cash_balance "Processing"
    out = hash_file_rows([processing, settled])
    assert len(out) == 1
    assert out[0]["cash_balance"] == "-83232.97"


def test_parse_strips_whitespace_in_text_fields(tmp_path):
    row = [ROW["run_date"], ROW["action"], " ", ROW["description"], ROW["type"], ROW["price"],
           ROW["quantity"], ROW["commission"], ROW["fees"], ROW["accrued_interest"],
           ROW["amount"], ROW["cash_balance"], ROW["settlement_date"]]
    p = _write(tmp_path, CURRENT_HEADER, [row])
    assert parse_file(p)[0]["symbol"] == ""


def test_hash_file_rows_order_independent_pairing():
    a1 = dict(ROW, cash_balance="100")
    a2 = dict(ROW, cash_balance="200")
    file_a = hash_file_rows([dict(a1), dict(a2)])
    file_b = hash_file_rows([dict(a2), dict(a1)])
    assert sorted(r["row_hash"] for r in file_a) == sorted(r["row_hash"] for r in file_b)


def test_hash_file_rows_canonicalizes_numeric_strings():
    plain = dict(ROW, quantity="0", amount="2000", cash_balance="2121.77")
    padded = dict(ROW, quantity="0.000", amount="2000.00", cash_balance="2121.770")
    assert row_hash(plain) == row_hash(padded)
    out = hash_file_rows([plain, padded])
    assert len(out) == 1
